#!/usr/bin/env python3
"""
Pull the HMC input parameters out of a Chroma LIME gauge configuration header.

    lime_hmc_params.py /path/to/cfg.lime                        # local file
    lime_hmc_params.py hpss:/home/w/wdetmold/clover-iso/.../cfg_1000.lime   # via `hsi get -`
    lime_hmc_params.py ... --toml                               # print a [lqcd] block to paste into an ensemble TOML

Chroma writes its full input XML into the SciDAC/ILDG records at the start of
every configuration it saves, so the gauge field is self-describing: beta,
clover coefficient, tadpole u0, stout smearing, masses, integrator, tau0,
save interval. This reads only the first few MB (default 4 MB) of the file,
which for an HPSS-resident file means streaming that much and stopping; the
file must be on the HPSS disk cache or it will be staged from tape first
(`hsi ls -X <file>` shows which).

Output is JSON by default: every value found, plus `masses`, the distinct
<Mass> values in order of first appearance (sea masses and Hasenbusch
preconditioner masses are not distinguished here; the smallest-magnitude and
largest-magnitude ones are usually the sea light/strange pair for 2+1
flavours, and the file name says which). Nothing is guessed: a tag that is
not in the header is absent from the output.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys

TAGS = {
    # tag -> output key, converter
    "beta": ("beta", float),
    "u0": ("gauge_u0", float),
    "clovCoeff": ("csw", float),
    "rho": ("stout_rho", float),
    "n_smear": ("stout_n_smear", int),
    "tau0": ("tau0", float),
    "SaveInterval": ("save_interval", int),
    "NWarmUpUpdates": ("n_warmup_updates", int),
    "nrow": ("nrow", str),
    "boundary": ("fermion_bc", str),
    "anisoP": ("anisotropic", lambda s: s.strip().lower() == "true"),
    "chroma": ("chroma_version", str),
    "qdp": ("qdp_version", str),
    "lowerMin": ("rational_lower_min", float),
    "upperMax": ("rational_upper_max", float),
}


def read_head(src: str, nbytes: int) -> bytes:
    if src.startswith("hpss:"):
        p = subprocess.Popen(["hsi", "-q", f"get - : {src[5:]}"], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        data = p.stdout.read(nbytes)
        p.kill()
        return data
    with open(src, "rb") as fh:
        return fh.read(nbytes)


def first(text: str, tag: str) -> str | None:
    m = re.search(rf"<{tag}>\s*([^<]*?)\s*</{tag}>", text)
    return m.group(1) if m else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="local path, or hpss:<absolute HPSS path>")
    ap.add_argument("--bytes", type=int, default=4_000_000, help="how much of the file to read")
    ap.add_argument("--toml", action="store_true", help="print as a [lqcd] TOML fragment instead of JSON")
    args = ap.parse_args()

    raw = read_head(args.source, args.bytes)
    text = raw.decode("latin-1")  # binary-safe; the XML is ASCII
    if "<Params>" not in text and "<beta>" not in text:
        sys.exit("no Chroma input XML found in the first bytes; is this a Chroma-written LIME file?")

    out = {"source": args.source}
    for tag, (key, conv) in TAGS.items():
        v = first(text, tag)
        if v is not None:
            try:
                out[key] = conv(v)
            except ValueError:
                out[key] = v
    masses = []
    for m in re.findall(r"<Mass>\s*([^<]+?)\s*</Mass>", text):
        f = float(m)
        if f not in masses:
            masses.append(f)
    if masses:
        out["masses"] = masses
    names = re.findall(r"<Name>([A-Z_0-9]+)</Name>", text)
    for key, pattern in (("gauge_action", r".*GAUGEACT$"), ("integrator", r"^LCM_.*"), ("fermion_state", r".*FERM_STATE$")):
        hit = next((n for n in names if re.match(pattern, n)), None)
        if hit:
            out[key] = hit
    steps = re.findall(r"<n_steps>(\d+)</n_steps>", text)
    if steps:
        out["n_steps_outer"] = int(steps[0])
        if len(steps) > 1:
            out["n_steps_inner"] = [int(s) for s in steps[1:]]
    nf = re.findall(r"<num_flavors>(\d+)</num_flavors>", text)
    if nf:
        out["logdet_num_flavors"] = [int(n) for n in nf]

    if not args.toml:
        json.dump(out, sys.stdout, indent=1)
        print()
        return 0

    nrow = out.get("nrow", "").split()
    print("# generated by lime_hmc_params.py from", args.source)
    print("[lqcd]")
    if out.get("beta") is not None:
        print(f"beta = {out['beta']}")
    if len(nrow) == 4:
        print(f"Nx = {nrow[0]}\nNy = {nrow[1]}\nNz = {nrow[2]}\nNt = {nrow[3]}")
        print(f"volume = [{', '.join(nrow)}]")
    print("\n[lqcd.action]")
    if "gauge_action" in out:
        print(f'gauge = "{out["gauge_action"].replace("_GAUGEACT", "")}"')
    if "gauge_u0" in out:
        print(f"gauge_u0 = {out['gauge_u0']}")
    print('fermion = "clover"')
    if "fermion_state" in out:
        print(f'fermion_state = "{out["fermion_state"]}"')
    if "csw" in out:
        print(f"csw = {out['csw']}")
    if "anisotropic" in out:
        print(f"anisotropic = {str(out['anisotropic']).lower()}")
    if "fermion_bc" in out:
        print(f'fermion_bc = "{out["fermion_bc"]}"')
    if masses:
        print("\n# distinct <Mass> values in the input (sea + Hasenbusch); set light/strange yourself")
        print(f"# masses = {masses}")
    print("\n[lqcd.smearing]")
    if "stout_rho" in out:
        print(f'type = "stout"\nrho = {out["stout_rho"]}\nn_smear = {out.get("stout_n_smear", 1)}')
    print("\n[lqcd.hmc]")
    for key in ("tau0", "save_interval", "n_warmup_updates", "rational_lower_min", "rational_upper_max"):
        if key in out:
            print(f"{key} = {out[key]}")
    if "integrator" in out:
        print(f'integrator = "{out["integrator"]}"')
    if "n_steps_outer" in out:
        print(f"n_steps = {out['n_steps_outer']}")
    if "chroma_version" in out:
        print(f'code_version = "chroma {out["chroma_version"]}"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
